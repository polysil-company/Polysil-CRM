"""The client's requirements, traced to the specs that built them and the tests
that hold them (test build-out 1).

    python scripts/generate_req_coverage.py      # writes docs/testing/REQ-Coverage.md

Three hops, each read from the files themselves, never typed by hand:

1. docs/client/Requirements.md: every `| REQ-nnn | ... |` row.
2. docs/specs/features/FS-*.md: the REQ ids named in each spec's header (the first
   lines, where "Requirement:" sits).
3. tests/**/*.py: the FS ids a test file names (docstrings and comments), and how
   many `test_` functions the file holds.

A REQ with no spec, or a spec with no test file, is listed first: those are the
rows the UAT script cannot cite yet.
"""

# ruff: noqa: E501  (table rows)

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQS = ROOT / "docs" / "client" / "Requirements.md"
SPECS = ROOT / "docs" / "specs" / "features"
TESTS = ROOT / "tests"
OUT = ROOT / "docs" / "testing" / "REQ-Coverage.md"

_REQ_ROW = re.compile(r"^\|\s*(REQ-\d{3,4})\s*\|\s*([^|]+?)\s*\|")
_REQ_ID = re.compile(r"REQ-(\d{3,4})")
# "REQ-1201 to 1210", "REQ-1201 to REQ-1210"
_REQ_RANGE = re.compile(r"REQ-(\d{3,4})\s+to\s+(?:REQ-)?(\d{3,4})")
# "REQ-1201, 1202, 1205": the prefix written once for a list
_REQ_LIST = re.compile(r"REQ-\d{3,4}((?:\s*,\s*\d{3,4}\b)+)")

# Specs that built a requirement without naming it in their header. Each row is
# the "built by" of the Field Notes' user-stories table, checked against the spec.
BUILT_WITHOUT_NAMING: dict[str, tuple[str, ...]] = {
    "REQ-001": ("FS-002a",),
    "REQ-006": ("FS-011", "FS-013", "FS-049"),
    "REQ-008": ("FS-001", "FS-041"),
    "REQ-103": ("FS-003a",),
    "REQ-302": ("FS-014",),
    "REQ-304": ("FS-014",),
    "REQ-305": ("FS-013", "FS-031"),
    "REQ-605": ("FS-007",),
    "REQ-704": ("FS-002", "FS-020"),
    "REQ-1302": ("FS-001", "FS-006"),
    "REQ-1303": ("FS-006",),
}
_FS_FILE = re.compile(r"^(FS-\d{3}[a-z]?)")
_FS_ID = re.compile(r"\bFS-(\d{3}[a-z]?)\b")
_TEST_FN = re.compile(r"^(?:async )?def test_", re.M)
HEADER_LINES = 12


def requirements() -> dict[str, str]:
    out: dict[str, str] = {}
    for line in REQS.read_text(encoding="utf-8").splitlines():
        m = _REQ_ROW.match(line)
        if m and m.group(1) not in out:
            out[m.group(1)] = m.group(2)
    return out


def specs_by_req() -> dict[str, set[str]]:
    out: dict[str, set[str]] = defaultdict(set)
    for path in sorted(SPECS.glob("FS-*.md")):
        m = _FS_FILE.match(path.name)
        if not m:
            continue
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:HEADER_LINES])
        for n in _REQ_ID.findall(head):
            out[f"REQ-{n}"].add(m.group(1))
        for tail in _REQ_LIST.findall(head):
            for n in re.findall(r"[0-9]{3,4}", tail):
                out[f"REQ-{n}"].add(m.group(1))
        for lo, hi in _REQ_RANGE.findall(head):
            for n in range(int(lo), int(hi) + 1):
                out[f"REQ-{n:03d}"].add(m.group(1))
    for req, specs in BUILT_WITHOUT_NAMING.items():
        out[req].update(specs)
    return out


def tests_by_spec() -> dict[str, dict[str, int]]:
    """FS id -> {test file: number of test functions}."""
    out: dict[str, dict[str, int]] = defaultdict(dict)
    for path in sorted(TESTS.rglob("test_*.py")):
        source = path.read_text(encoding="utf-8")
        n = len(_TEST_FN.findall(source))
        if not n:
            continue
        rel = path.relative_to(ROOT).as_posix()
        for fs in set(_FS_ID.findall(source)):
            out[f"FS-{fs}"][rel] = n
    return out


def render() -> str:
    reqs = requirements()
    by_req = specs_by_req()
    by_spec = tests_by_spec()
    rows = []
    gaps = []
    total_files: set[str] = set()
    for req, title in reqs.items():
        specs = sorted(by_req.get(req, set()))
        files: dict[str, int] = {}
        for fs in specs:
            files.update(by_spec.get(fs, {}))
        total_files |= set(files)
        tests = sum(files.values())
        untested = [fs for fs in specs if not by_spec.get(fs)]
        rows.append((req, title, specs, len(files), tests, untested))
        if not specs or untested:
            gaps.append((req, title, specs, untested))

    lines = [
        "# Requirements to specs to tests",
        "",
        "> Generated by `scripts/generate_req_coverage.py`. **Never hand-edit.**",
        "",
        f"{len(reqs)} requirements from `docs/client/Requirements.md`. "
        f"{sum(1 for r in rows if r[2])} are named by at least one spec; "
        f"{sum(1 for r in rows if r[4])} reach at least one test, through {len(total_files)} test files.",
        "",
        "A test file counts for a spec when it names the spec's id. The count is test functions",
        "in those files, so it says where to look, not how thorough the tests are.",
        "",
        "## Not traced yet",
        "",
        "| REQ | Requirement | Specs | Specs with no test file |",
        "|---|---|---|---|",
    ]
    for req, title, specs, untested in gaps:
        lines.append(f"| {req} | {title} | {', '.join(specs) or 'none'} | {', '.join(untested) or ''} |")
    lines += ["", "## Every requirement", "",
              "| REQ | Requirement | Specs | Test files | Tests |", "|---|---|---|---|---|"]
    for req, title, specs, n_files, tests, _ in rows:
        lines.append(f"| {req} | {title} | {', '.join(specs) or '-'} | {n_files} | {tests} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
